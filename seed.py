def seed_students():
    conn = get_db_connection()
    cursor = conn.cursor()
    count = 0
    for student_id, name in STUDENTS:
        try:
            cursor.execute(
                "INSERT INTO students (student_id, name) VALUES (%s, %s)",
                (student_id, name)
            )
            count += 1
        except Exception:
            conn.rollback()  # rollback failed insert before continuing
            pass
    conn.commit()
    cursor.close()
    conn.close()
    print(f"Seeded {count} students successfully.")

